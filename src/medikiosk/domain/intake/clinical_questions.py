def normalize_language(lang: str) -> str:
    """Normalize language code to one of the 8 scheduled languages."""
    code = (lang or "").lower().strip()
    for supported in SUPPORTED_LANGUAGES:
        if code.startswith(supported):
            return supported
    return "en"


def detect_symptom_category(text: str, history: list[str] | None = None) -> str:
    """Detect symptom category from current response or prior conversation history."""
    if text:
        for cat, pattern in _SYMPTOM_PATTERNS:
            if pattern.search(text):
                return cat

    if history:
        for prev in reversed(history):
            if not prev:
                continue
            for cat, pattern in _SYMPTOM_PATTERNS:
                if pattern.search(prev):
                    return cat

    return "general"


def generate_next_question(
    response_text: str,
    turn_index: int = 1,
    lang: str = "en",
    history: list[str] | None = None,
) -> str:
    """Generate dynamic next clinical question following SOCRATES protocol.

    Args:
        response_text: Current patient utterance.
        turn_index: Number of responses received (1-indexed or 0-indexed).
        lang: Patient's preferred language code.
        history: Optional list of previous responses in the session.

    Returns:
        Localised clinical question string.
    """
    norm_lang = normalize_language(lang)

    # Initial prompt when no responses have been processed
    if turn_index == 0 and not response_text.strip():
        return CHIEF_COMPLAINT_QUESTIONS.get(norm_lang, CHIEF_COMPLAINT_QUESTIONS["en"])

    category = detect_symptom_category(response_text, history)
    dialogue = _CLINICAL_QUESTIONS.get(category, _CLINICAL_QUESTIONS["general"])

    # Effective SOCRATES step (step 1 to 4)
    effective_turn = max(1, turn_index)
    if effective_turn in dialogue:
        questions = dialogue[effective_turn]
        return questions.get(norm_lang, questions.get("en", ""))

    # Turn 5+ conclusion
    return _CONCLUSION_QUESTIONS.get(norm_lang, _CONCLUSION_QUESTIONS["en"])
