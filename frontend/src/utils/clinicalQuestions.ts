/**
 * Normalizes language codes to the 8 supported scheduled languages,
 * falling back gracefully to 'en' or 'hi'.
 */
export function normalizeLanguage(lang: string): SupportedLanguage {
  const code = (lang || '').toLowerCase().trim();
  if (code.startsWith('hi')) return 'hi';
  if (code.startsWith('bn')) return 'bn';
  if (code.startsWith('ta')) return 'ta';
  if (code.startsWith('te')) return 'te';
  if (code.startsWith('mr')) return 'mr';
  if (code.startsWith('gu')) return 'gu';
  if (code.startsWith('kn')) return 'kn';
  if (code.startsWith('en')) return 'en';
  return 'en';
}

/**
 * Detects the clinical symptom category from patient response text.
 */
export function detectSymptomCategory(text: string): SymptomCategory {
  if (!text) return 'general';
  for (const { category, regex } of SYMPTOM_PATTERNS) {
    if (regex.test(text)) {
      return category;
    }
  }
  return 'general';
}

/**
 * In-memory active symptom category tracker across turns for the current dialogue session.
 */
let currentDialogueCategory: SymptomCategory = 'general';

/**
 * Resets the in-memory dialogue tracker to 'general'.
 */
export function resetClinicalDialogue(): void {
  currentDialogueCategory = 'general';
}

/**
 * Helper to get the initial question for a language.
 */
export function getInitialQuestion(lang: string): string {
  const normLang = normalizeLanguage(lang);
  return INITIAL_QUESTIONS[normLang] || INITIAL_QUESTIONS.en;
}

/**
 * Helper to get quick reply chips for a language.
 */
export function getQuickReplies(lang: string, symptomOrResponse?: string): string[] {
  const normLang = normalizeLanguage(lang);
  if (symptomOrResponse) {
    const cat = detectSymptomCategory(symptomOrResponse);
    if (cat !== 'general') {
      return DIALOGUES[cat].turn1[normLang].quickReplies;
    }
  }
  return INITIAL_QUICK_REPLIES[normLang] || INITIAL_QUICK_REPLIES.en;
}

/**
 * Helper that builds a FollowUpResponse whose toString() evaluates to the question string.
 */
function createFollowUpResponse(question: string, quickReplies: string[]): FollowUpResponse {
  return {
    question,
    quickReplies,
    toString(): string {
      return this.question;
    },
  };
}

/**
 * Generates responsive, intelligent clinical follow-up questions and tailored
 * quick reply chips according to the SOCRATES protocol in any of the 8 scheduled languages.
 *
 * Supports polymorphic argument signatures:
 *   1) (lastResponse: string, turnIndex: number, lang: string) -> Primary SOCRATES generator
 *   2) (lang: string, lastResponse: string, turnIndex: number) -> Adapter for legacy callers
 *
 * @param arg1 Patient response text OR language code
 * @param arg2 Turn index (number) OR patient response text (string)
 * @param arg3 Language code (string) OR turn index (number)
 * @returns FollowUpResponse with .question, .quickReplies, and toString() support.
 */
export function getFollowUpQuestion(
  arg1: string,
  arg2?: number | string,
  arg3?: string | number
): FollowUpResponse {
  let lastResponse: string;
  let turnIndex: number;
  let lang: string;

  if (typeof arg2 === 'number') {
    // Standard signature: getFollowUpQuestion(lastResponse, turnIndex, lang)
    lastResponse = arg1 || '';
    turnIndex = arg2;
    lang = typeof arg3 === 'string' ? arg3 : 'en';
  } else if (typeof arg2 === 'string') {
    // Inverted signature: getFollowUpQuestion(lang, lastResponse, turnIndex)
    lang = arg1 || 'en';
    lastResponse = arg2;
    turnIndex = typeof arg3 === 'number' ? arg3 : 1;
  } else {
    lastResponse = arg1 || '';
    turnIndex = 1;
    lang = 'en';
  }

  const normLang = normalizeLanguage(lang);

  // Turn 0 represents initial chief complaint request
  if (turnIndex === 0 && !lastResponse.trim()) {
    return createFollowUpResponse(
      INITIAL_QUESTIONS[normLang] || INITIAL_QUESTIONS.en,
      INITIAL_QUICK_REPLIES[normLang] || INITIAL_QUICK_REPLIES.en
    );
  }

  // Detect symptom category from lastResponse
  const detected = detectSymptomCategory(lastResponse);
  if (detected !== 'general') {
    currentDialogueCategory = detected;
  }

  // Map turnIndex (handling both 0-indexed and 1-indexed styles)
  const effectiveTurn = turnIndex <= 1 ? 1 : turnIndex;
  const dialogue = DIALOGUES[currentDialogueCategory] || DIALOGUES.general;

  let rawStep: { question: string; quickReplies: string[] };

  switch (effectiveTurn) {
    case 1:
      rawStep = dialogue.turn1[normLang] || dialogue.turn1.en;
      break;
    case 2:
      rawStep = dialogue.turn2[normLang] || dialogue.turn2.en;
      break;
    case 3:
      rawStep = dialogue.turn3[normLang] || dialogue.turn3.en;
      break;
    case 4:
      rawStep = dialogue.turn4[normLang] || dialogue.turn4.en;
      break;
    default:
      rawStep = CONCLUSION_QUESTIONS[normLang] || CONCLUSION_QUESTIONS.en;
      break;
  }

  return createFollowUpResponse(rawStep.question, rawStep.quickReplies);
}
